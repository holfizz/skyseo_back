/** Детерминированный генератор: одна и та же пара «сид+шаг» даёт одно и то же. */
function rng(seed: number): () => number {
	let s = seed >>> 0 || 1
	return () => {
		s ^= s << 13
		s >>>= 0
		s ^= s >> 17
		s ^= s << 5
		s >>>= 0
		return s / 4294967296
	}
}

function hash(text: string): number {
	let h = 2166136261
	for (let i = 0; i < text.length; i++) {
		h ^= text.charCodeAt(i)
		h = Math.imul(h, 16777619)
	}
	return h >>> 0
}

/** Утвердительные и отрицательные ответы со своими хвостами. */
const ANSWERS = {
	да: {
		head: ['да', 'ага', 'угу', 'вроде да', 'похоже, что да', 'да вроде', 'почти', 'думаю, да', 'скорее всего'],
		tail: ['', '', '', ', сейчас гляну', ', позже отпишу', ', перезвоню', ', минут через двадцать', ', уже почти'],
	},
	нет: {
		head: ['нет', 'пока нет', 'не получилось', 'ещё нет', 'вряд ли', 'не сегодня'],
		tail: ['', '', '', ', завтра посмотрю', ', попозже вернусь', ', давай перенесём', ', времени не было'],
	},
}

export type ChatLine = { text: string; role: ChatRole }

/**
 * Следующая реплика в разговоре.
 *
 * Роль выбирается из того, что уместно после предыдущей: на вопрос отвечают,
 * после ответа реагируют или прощаются. Без этого получался набор не связанных
 * между собой фраз — а именно связность отличает переписку от рассылки.
 */
export function nextLine(pairKey: string, index: number, previous?: ChatRole): ChatLine {
	const rnd = rng(hash(`${pairKey}:${index}`))

	const options = previous ? FLOW[previous] : (['начало', 'вопрос'] as ChatRole[])
	const role = options[Math.floor(rnd() * options.length)]

	const text =
		role === 'ответ'
			? (() => {
					const set = rnd() < 0.62 ? ANSWERS['да'] : ANSWERS['нет']
					return set.head[Math.floor(rnd() * set.head.length)] + set.tail[Math.floor(rnd() * set.tail.length)]
				})()
			: PARTS[role].map(slot => slot[Math.floor(rnd() * slot.length)]).join('')

	return { text: text.replace(/\s+/g, ' ').trim(), role }
}

/** Сколько всего разных реплик умеет собрать генератор — для проверки. */
export function variantCount(): number {
	const fromParts = Object.values(PARTS)
		.filter(slots => slots.length)
		.reduce((sum, slots) => sum + slots.reduce((n, s) => n * s.length, 1), 0)
	const fromAnswers = Object.values(ANSWERS).reduce((sum, a) => sum + a.head.length * a.tail.length, 0)
	return fromParts + fromAnswers
}
