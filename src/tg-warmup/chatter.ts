/**
 * Короткие реплики для переписки между своими аккаунтами.
 *
 * Зачем вообще. Исходящая история нужна для оценки аккаунта, но писать
 * незнакомым ради неё нельзя — за это и прилетает PEER_FLOOD. Поэтому аккаунты
 * из пула переписываются между собой.
 *
 * Почему не список фраз. Раньше их было четырнадцать, и на длинном прогреве
 * пара аккаунтов слала друг другу одно и то же по кругу — это заметнее, чем
 * молчание. Здесь реплика собирается из частей, и вариантов десятки тысяч.
 *
 * Почему не нейросеть. Соблазн был: владелец сам предложил. Но это платный
 * вызов на каждую реплику служебной болтовни, ещё одна точка отказа посреди
 * прогрева и уход текста наружу. Задача тут не в красоте языка, а в том, чтобы
 * сообщения были короткие, бытовые и разные — с этим справляется генератор.
 * Если однообразие всё же полезет, подключить модель можно поверх: точка
 * входа одна, nextLine.
 *
 * Реплики намеренно ни о чём: бытовой трёп двух знакомых. Никаких ссылок,
 * приглашений и предложений — ровно то, что не должно попасть в чужую жалобу.
 */

export type ChatRole = 'начало' | 'вопрос' | 'ответ' | 'реакция' | 'конец'

/** Что уместно сказать следующим, если предыдущая реплика была такой. */
const FLOW: Record<ChatRole, ChatRole[]> = {
	'начало': ['вопрос', 'ответ', 'реакция'],
	'вопрос': ['ответ'],
	'ответ': ['реакция', 'вопрос', 'конец'],
	'реакция': ['вопрос', 'конец', 'ответ'],
	'конец': ['начало'],
}

