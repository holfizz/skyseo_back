/**
 * Стоп-лист получателей: кому пул больше не пишет никогда.
 *
 * Зачем он именно общий, а не по аккаунту. Один и тот же человек попадает в
 * разные списки и получает сообщение с двух-трёх наших аккаунтов подряд. Если
 * он закрылся от первого, второй и третий — это уже три жалобы вместо одной, а
 * ограничивают аккаунт именно жалобы, а не объём отправки. Поэтому отказ,
 * полученный любым аккаунтом, закрывает адресата для всего пула.
 *
 * Здесь только чистые функции: как привести ключ к единому виду и как понять,
 * что в ответе был отказ. Хранение — в базе, проверка — в отправщике.
 */

/** Чем адресата опознаём. Юзернейм, телефон и id в Telegram — разные ключи. */
export type StopKind = 'username' | 'phone' | 'tgUserId'

export type StopKey = { kind: StopKind; value: string }

/**
 * Юзернейм к единому виду: без собаки, без ссылки, в нижнем регистре.
 * Один и тот же человек приходит и как «@ivan», и как «t.me/Ivan».
 */
export function normalizeUsername(raw?: string | null): string | null {
	if (!raw) return null
	const v = String(raw)
		.trim()
		.replace(/^https?:\/\//i, '')
		.replace(/^t\.me\//i, '')
		.replace(/^@/, '')
		.toLowerCase()
	return /^[a-z0-9_]{3,32}$/.test(v) ? v : null
}

/**
 * Телефон к единому виду: только цифры, российская восьмёрка приводится к семи.
 * Иначе «8 900 …» и «+7 900 …» — один человек в двух строках стоп-листа.
 */
export function normalizePhone(raw?: string | null): string | null {
	if (!raw) return null
	let v = String(raw).replace(/\D/g, '')
	if (v.length === 11 && v.startsWith('8')) v = '7' + v.slice(1)
	return v.length >= 10 && v.length <= 15 ? v : null
}

/** Все ключи, по которым этого адресата стоит искать и заносить. */
export function keysOf(r: { username?: string | null; phone?: string | null; tgUserId?: string | null }): StopKey[] {
	const out: StopKey[] = []
	const u = normalizeUsername(r.username)
	if (u) out.push({ kind: 'username', value: u })
	const p = normalizePhone(r.phone)
	if (p) out.push({ kind: 'phone', value: p })
	const id = r.tgUserId ? String(r.tgUserId).trim() : null
	if (id && /^\d+$/.test(id)) out.push({ kind: 'tgUserId', value: id })
	return out
}

/**
 * Отказы, после которых писать нельзя.
 *
 * Список намеренно короткий и однозначный. Просто «нет» сюда не входит: это
 * может быть ответом на вопрос из переписки, а не отказом от общения, и цена
 * ошибки несимметричная — лишняя строка в стоп-листе навсегда закрывает живого
 * человека, которого можно было дожать.
 *
 * Отсюда же граница: автомат заносит только по прямому отказу и по блокировке.
 * Всё, что звучит как «не сейчас» или «дорого», разбирает человек.
 */
const OPT_OUT = [
	'не интересно', 'неинтересно', 'не интересует', 'не интересны', 'не актуально',
	'нет спасибо', 'спасибо нет',
	'удалите меня', 'удали меня', 'удалите мой номер',
	'отпишите', 'отписаться', 'отпишись', 'отстаньте', 'отстань', 'отвали',
	'не пишите', 'не пиши мне', 'больше не пишите', 'больше не пиши',
	'не надо писать', 'не нужно писать', 'прекратите писать',
	'это спам', 'спамите', 'пожалуюсь', 'жалоба на вас',
]

/** Текст к виду, в котором его можно сравнивать: без ё, знаков и лишних пробелов. */
function flatten(text: string): string {
	return text
		.toLowerCase()
		.replace(/ё/g, 'е')
		.replace(/[^a-zа-я0-9]+/gi, ' ')
		.trim()
}

/**
 * Это отказ? Возвращает сработавшую фразу — её видно в карточке стоп-листа,
 * чтобы человек мог проверить решение автомата, а не верить ему на слово.
 */
export function optOutReason(text?: string | null): string | null {
	if (!text) return null
	const flat = flatten(text)
	if (!flat) return null
	return OPT_OUT.find(p => flat.includes(p)) ?? null
}
