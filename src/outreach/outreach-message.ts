// Текст холодного сообщения. Структура утверждена заказчиком — менять нельзя.
// Отдельно оговорено: НЕ обещаем сроки и НЕ считаем трафик в переходах.
//
// В самом тексте не должно быть длинных тире и буквы «ё»: заказчик считает,
// что они выдают машинный набор. Отчёт лид получает файлом от менеджера,
// поэтому ссылки в сообщении нет.

export type MessageKeyword = { keyword: string; position: number }
export type MessageCompetitor = { domain: string; position: number }

export type MessageInput = {
	domain: string
	firstName?: string | null
	middleName?: string | null
	// ключи лида, отсортированные по позиции: лучшие первыми
	keywords: MessageKeyword[]
	// домены с 9 и 10 мест по ключам лида
	competitors: MessageCompetitor[]
	// суммарная частотность показанных запросов по Вордстату
	volume?: number | null
}

const MAX_KEYWORDS_SHOWN = 3

/**
 * Окно позиций, из которого берём запросы для текста.
 *
 * Лид попадает в рассылку из-за ОДНОГО запроса, где он на 15-50 месте, но по
 * другим запросам того же прогона он может стоять в топ-3. Раньше в письмо
 * подставлялись его ЛУЧШИЕ позиции, и получалось «вы на 1 месте, выше вас
 * такие-то, давайте поднимем в топ-10». Разговор на этом заканчивался.
 *
 * Берём только те запросы, где человеку есть что улучшать.
 */
export const MESSAGE_POSITION_MIN = 10
export const MESSAGE_POSITION_MAX = 50

/**
 * Спрос по показанным запросам.
 *
 * В тексте письма он больше не фигурирует: заказчик заменил фразу про
 * количество запросов на обещание прислать отчёт, где эта цифра и будет.
 * Функция оставлена, потому что её зовут при импорте и хранят результат —
 * он нужен отчёту и для оценки лида.
 */
export function sumShownVolume(keywords: MessageKeyword[], volumes: Map<string, number>): number {
	return keywords
		.slice(0, MAX_KEYWORDS_SHOWN)
		.reduce((sum, k) => sum + (volumes.get(k.keyword) ?? 0), 0)
}

/**
 * Точка в конце абзаца не ставится, внутри абзаца остаётся.
 *
 * Правило заказчика: «ваши услуги. Бесплатно» — точка между предложениями нужна,
 * а на последнем слове абзаца её быть не должно, иначе текст выглядит как
 * официальное письмо, а не как сообщение живого человека в мессенджере.
 *
 * Снимаем только точку: вопросительный знак у «Прислать?» обязан остаться.
 */
function trimDot(text: string): string {
	return text.replace(/\.$/, '')
}

/**
 * Второе сообщение — уходит после того, как человек ответил на открывающее.
 *
 * Структура утверждена заказчиком: что увидели, кто выше, чем занимаемся,
 * предложение отчёта. Первые два блока собираются из данных и ПРОПУСКАЮТСЯ,
 * если данных нет: лид, заведённый руками без прогона парсера, не должен
 * получить письмо с пустыми кавычками и фразой «эти запросы» ни о чём.
 * Последние два блока постоянные — это рассказ о нас, он от данных не зависит.
 *
 * Позиции идут одной фразой, а не столбиком: списком это читается как отчёт
 * робота, а нужен разговор.
 */
export function buildOutreachMessage(input: MessageInput): string {
	const blocks: string[] = []

	// Позиции: первая с словом «месте», дальше без повтора.
	const shown = input.keywords.slice(0, MAX_KEYWORDS_SHOWN)
	if (shown.length > 0) {
		const parts = shown.map((k, i) =>
			i === 0 ? `по «${k.keyword}» вы на ${k.position} месте` : `по «${k.keyword}» на ${k.position}`,
		)
		blocks.push(`Посмотрели ваш сайт в поиске Яндекса - ${parts.join(', ')}.`)
	} else {
		blocks.push('Посмотрели ваш сайт в поиске Яндекса.')
	}

	const rivals = input.competitors.slice(0, 2)
	if (rivals.length >= 2) {
		blocks.push(
			`Выше вас ${rivals[0].domain} и ${rivals[1].domain} - почти весь трафик по этим запросам уходит к ним.`,
		)
	} else if (rivals.length === 1) {
		blocks.push(`Выше вас ${rivals[0].domain} - почти весь трафик по этим запросам уходит к нему.`)
	}

	blocks.push(
		'Мы занимаемся продвижением сайтов в топ-10 Яндекса. Из поиска переходы идут ' +
			'бесплатно, в отличие от Директа, где вы платите за каждый клик. Работаем по ' +
			'позициям - рост видно в отчете, платите за результат.',
	)

	blocks.push(
		'Давайте пришлю бесплатный отчет: где вы сейчас, кто выше и сколько людей в месяц ' +
			'ищет эти запросы. Посмотрите - если интересно, обсудим, как поднять. Прислать?',
	)

	return blocks.map(trimDot).join('\n\n')
}

// Доменные зоны второго уровня: после срезания «.uk» надо срезать и «.co».
const SECOND_LEVEL = ['com', 'co', 'net', 'org']

/**
 * Имя сайта без зоны: «dreamsstore.ru» → «dreamsstore».
 *
 * В первом сообщении зона только мешает: она не несёт смысла, а адрес с точкой
 * Telegram превращает в ссылку, и живое обращение начинает выглядеть рассылкой.
 * В остальных текстах домены остаются целиком: там это чужие сайты, и по
 * огрызку конкурента лид его не узнает.
 */
export function siteName(domain: string): string {
	const clean = (domain || '').trim().toLowerCase().replace(/^https?:\/\//, '').replace(/^www\./, '').replace(/\/.*$/, '')
	const parts = clean.split('.')
	if (parts.length < 2) return clean
	parts.pop()
	if (parts.length > 1 && SECOND_LEVEL.includes(parts[parts.length - 1])) parts.pop()
	return parts.join('.')
}

/**
 * Открывающее сообщение — первое касание в Telegram.
 *
 * Структура утверждена заказчиком: обращение по имени и отчеству, фраза про
 * ожидание подходящего дня, вопрос про сайт и подпись «Я по работе».
 *
 * Фраза про день недели меняется в зависимости от того, КОГДА менеджер открыл
 * лида: в выходные пишем «дождался выходных», в будни «ждал будние». Смысл
 * один: показать, что писали не веерной рассылкой в случайный момент, а
 * выбирали время. Поэтому сообщение и не хранится в базе, а собирается при
 * каждом обращении: сохранённый текст к понедельнику начал бы врать.
 *
 * Подпись «Я по работе» обязательна: без неё сообщение от незнакомого аккаунта
 * читается как личное и его закрывают, не дочитав.
 */
export function buildOpeningMessage(input: MessageInput, now: Date = new Date()): string {
	const first = input.firstName?.trim()
	const middle = input.middleName?.trim()
	const name = [first, middle].filter(Boolean).join(' ')

	const day = now.getDay()
	const isWeekend = day === 0 || day === 6
	const waited = isWeekend
		? 'ждал выходные, чтобы вам написать'
		: 'ждал будние, чтобы вам написать'

	const hello = name ? `${name}, здравствуйте, ${waited}` : `Здравствуйте, ${waited}`

	// Пробел перед вопросительным знаком поставлен намеренно, так утвердил заказчик.
	// Изначально он спасал от того, что Telegram затягивал «?» внутрь ссылки;
	// теперь зону из домена срезает siteName и ссылки не возникает вовсе,
	// но вид строки остаётся прежним.
	return `${hello}\n\nМогу с вами пообщаться по поводу сайта - ${siteName(input.domain)} ?\nЯ по работе`
}
