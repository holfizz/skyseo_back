/**
 * ФИО из реестров и парсеров приходит капсом: «ГОРЛАЧЕВ СЕРГЕЙ РУСЛАНОВИЧ».
 * В обращении это выглядит криком и сразу выдаёт рассылку. Приводим к обычному
 * виду: «Горлачев Сергей Русланович».
 *
 * Строку, где уже есть строчные буквы, НЕ трогаем: значит, регистр проставлен
 * руками (в том числе нестандартный), и ломать его нельзя. Поэтому нормализуем
 * КАЖДОЕ поле по отдельности, а не склеенное ФИО: иначе одно поле с капсом
 * рядом с обычным («Юрий ЮРЬЕВИЧ») уже содержит строчные и осталось бы как есть.
 */
export function normalizeName(value?: string | null): string {
	const s = (value ?? '').trim()
	if (!s || /\p{Ll}/u.test(s)) return s
	return s.toLowerCase().replace(/(^|[\s\-–—])(\p{L})/gu, (_, sep, ch) => sep + ch.toUpperCase())
}
