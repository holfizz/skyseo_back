  WHEN 'hyp-2026-10-h2' THEN 'hyp-2026-10-call-h2'
  WHEN 'hyp-2026-10-h3' THEN 'hyp-2026-10-call-h3'
  WHEN 'hyp-2026-10-h4' THEN 'hyp-2026-10-call-h4'
  ELSE "hypothesisId"
END
WHERE
  "hypothesisId" IN (
    'hyp-2026-10-h0',
    'hyp-2026-10-h1',
    'hyp-2026-10-h2',
