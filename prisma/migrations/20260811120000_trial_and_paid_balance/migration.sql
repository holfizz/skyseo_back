-- Продвижение по подписке: бесплатная неделя + оплаченные дни вместо баллов.
-- Написана руками (shadow-DB ломает мина 1780430548), как и миграции CRM.
--
-- Аддитивная: существующие колонки не трогаем. Откат = DROP трёх колонок.
--
-- Модель после этой миграции:
--   users.balance    — валюта участника сети (заработок в приложении), выводится рублями.
--                      Продвижение за неё НЕ оплачивается.
--   users.paidUntil  — до какой даты оплачено продвижение. Триал даёт +7 дней,
--                      оплата продлевает на месяц. Единственный источник правды для гейта.
--
-- ВАЖНО: бэкфилл (3) обязателен. Без него в момент выката встанет продвижение
-- у всех, кто уже заплатил, — а бэкфилл (2) нужен, чтобы существующие юзеры
-- не получили новую бесплатную неделю.

-- ─── 1. Новые колонки ───

-- До какой даты оплачено продвижение. NULL = не оплачено.
ALTER TABLE "users" ADD COLUMN "paidUntil" TIMESTAMP(3);

-- Старт бесплатной недели. NULL = триал ещё не начинался.
ALTER TABLE "users" ADD COLUMN "trialStartedAt" TIMESTAMP(3);

-- Когда сайт одобрен админом. Раньше был только флаг isApproved без времени.
ALTER TABLE "websites" ADD COLUMN "approvedAt" TIMESTAMP(3);

-- ─── 2. Бэкфилл trialStartedAt ───
-- Всем, у кого уже есть ключи, ставим дату ПЕРВОГО ключа: их неделя давно прошла.
-- Кто ключей ещё не заводил — остаётся NULL и получит свою неделю честно,
-- когда создаст первый ключ и сайт одобрят.
UPDATE "users" u
SET "trialStartedAt" = sub."firstTaskAt"
FROM (
    SELECT w."userId" AS uid, MIN(t."createdAt") AS "firstTaskAt"
    FROM "tasks" t
    JOIN "websites" w ON w."id" = t."websiteId"
    GROUP BY w."userId"
) sub
WHERE u."id" = sub.uid;

-- ─── 3. Бэкфилл paidUntil — переходный месяц ───
-- У кого на балансе ещё были баллы, тот платил за продвижение и рассчитывал на него.
-- Даём 30 дней с момента миграции, чтобы никого не отрезало в момент выката;
-- за этот месяц люди переедут на подписку.
--
-- РЕШЕНИЕ ДЛЯ ВЛАДЕЛЬЦА: порог `balance > 0` выбран как «был непотраченный бюджет».
-- Если хочешь дать переходный месяц только тем, кто реально платил, замени условие на
-- EXISTS (SELECT 1 FROM payments p WHERE p."userId" = u."id" AND p."status" = 'SUCCEEDED').
UPDATE "users" u
SET "paidUntil" = NOW() + INTERVAL '30 days'
WHERE u."balance" > 0;

-- ─── 4. Бэкфилл approvedAt ───
-- Реального времени одобрения в истории нет — берём дату создания сайта.
-- Приблизительно, но безопасно: у этих юзеров триал всё равно закрыт пунктом 2.
UPDATE "websites" SET "approvedAt" = "createdAt" WHERE "isApproved" = true;
