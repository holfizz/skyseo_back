const assert=require('node:assert/strict')
const {outgoingAllowance}=require('../dist/src/tg-warmup/warmup-plan')
const {TgWarmupService}=require('../dist/src/tg-warmup/tg-warmup.service')
const {CampaignService,maySend}=require('../dist/src/tg-warmup/campaign.service')
const {PrismaClient}=require('@prisma/client')
assert.equal(new URL(process.env.DATABASE_URL).pathname,'/skyseo_workspace_test','Dedicated test DB only')
const db=new PrismaClient(), day=86400000
const input={dayIndex:0,ageDays:0,daysManaged:1,premium:true,outreachDays:null,actionsTotal:0,dialogs:0,channels:0,profileFilled:0,spamBlock:'clean',floodWaits:0,peerFloods:0}
async function main(){
 for(const daysManaged of [0,0.99]) assert.equal(outgoingAllowance({...input,daysManaged}).dailyMessages,0)
 for(const premium of [false,undefined]) assert.equal(outgoingAllowance({...input,premium}).dailyMessages,0)
 for(const outreachDays of [null,0,1,1.999]) assert.equal(outgoingAllowance({...input,daysManaged:30,outreachDays}).dailyMessages,15)
 const full=outgoingAllowance({...input,outreachDays:2});assert.equal(full.dailyMessages,500);assert.equal(full.maxJoinsPerDay,0);assert.equal(full.maxReactionsPerDay,0)
 for(const patch of [{floodWaits:1},{peerFloods:1},{throttle:{factor:0.6,until:null,reason:'restriction'}}]) assert.ok(outgoingAllowance({...input,outreachDays:5,...patch}).dailyMessages<=15)
 for(const patch of [{spamBlock:'temporary'},{spamBlock:'permanent'},{peerFloods:2},{floodWaits:6}]) assert.equal(outgoingAllowance({...input,outreachDays:5,...patch}).dailyMessages,0)
 assert.equal(maySend({forceSend:true},{allowOutgoing:false}),false)
 const warmup=new TgWarmupService(db,{}), campaigns=new CampaignService(db,warmup,{}, {})
 assert.equal(await warmup.tick(),0);assert.equal(await warmup.ensureUpkeep(),0)
 await assert.rejects(()=>warmup.startWarmup(['x'],7),/отключён/)
 await assert.rejects(()=>warmup.setForceSend('x',true),/отключён/)
 const account=await db.tgAccount.create({data:{session:'test-only',apiId:1,apiHash:'test',deviceModel:'test',systemVersion:'test',appVersion:'test',langCode:'ru',systemLangCode:'ru',status:'READY',forceSend:true,probe:{premium:true,spamBlock:'clean'},premiumCheckedAt:new Date(),purchasedAt:new Date()}})
 const c=await campaigns.create({name:'premium policy isolated test'})
 try {
  assert.equal(await warmup.claimAccount(account.id,'poll',10),false,'No read/poll connection during first24h')
  assert.equal((await warmup.allowanceFor(account,0)).dailyMessages,0)
  let a=await db.tgAccount.update({where:{id:account.id},data:{purchasedAt:new Date(Date.now()-10*day)}})
  assert.equal(await warmup.claimAccount(a.id,'poll',10),true);await warmup.releaseAccount(a.id)
  assert.equal((await warmup.allowanceFor(a,0)).dailyMessages,15,'Old purchase without sending still ramps')
  const q=await campaigns.dailyQuota({perAccountPerDay:100,accounts:[{account:a,accountId:a.id,dailyLimit:100}]},'2026-10-01')
  assert.equal(q.get(a.id),15,'forceSend and manual dailyLimit cannot bypass ramp')
  await db.tgRecipient.createMany({data:Array.from({length:15},(_,i)=>({campaignId:c.id,accountId:a.id,username:'test'+i,status:'SENT',sentAt:new Date()}))})
  assert.equal((await warmup.allowanceFor(a,0)).maxMessagesPerDay,0,'Budget exhausted globally')
  a=await db.tgAccount.update({where:{id:a.id},data:{outreachStartedAt:new Date(Date.now()-2*day)}})
  assert.equal((await warmup.allowanceFor(a,0)).dailyMessages,500)
  a=await db.tgAccount.update({where:{id:a.id},data:{premiumCheckedAt:new Date(Date.now()-2*day)}})
  assert.equal((await warmup.allowanceFor(a,0)).dailyMessages,0,'Expired Premium check prevents sending')
 } finally { await db.tgCampaign.delete({where:{id:c.id}});await db.tgAccount.delete({where:{id:account.id}}) }
 console.log('PASS Premium required, 24h no connections, two-day ramp starts with outreach, no background, no force bypass, shared budget and restriction gates')
}
main().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>db.$disconnect())
